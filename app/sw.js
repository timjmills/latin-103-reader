const abs = (rel) => new URL(rel, self.location.href).href;

/** The caches of earlier versions, each with the fingerprints it was filled under ({} for one from before them). */
async function earlierCaches() {
  const out = [];
  for (const name of await caches.keys()) {
    if (!name.startsWith('latin103-') || name === SHELL || name === RUNTIME) continue;
    const cache = await caches.open(name);
    let hashes = {};
    try { const m = await cache.match(abs(HASH_KEY)); if (m) hashes = await m.json(); } catch { hashes = {}; }
    out.push({ cache, hashes });
  }
  return out;
}
/** './rel/path' of a same-scope URL, the shape HASHES uses. */
const relOf = (url) => `./${new URL(url).pathname.slice(scopePath().length)}`;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL);
    const earlier = await earlierCaches();
    // An earlier copy of `rel` whose content is this version's (same fingerprint), or null.
    const unchanged = async (rel) => {
      const h = HASHES[rel];
      if (!h) return null;
      for (const { cache: c, hashes } of earlier) {
        if (hashes[rel] !== h) continue;
        const r = await c.match(abs(rel), { ignoreSearch: true });
        if (r) return r;
      }
      return null;
    };
    // In chunks, not all ~180 at once: a phone that opened every connection in one Promise.all stalled the install (m9).
    const CHUNK = 12;
    const one = async (rel) => {
      try {
        const kept = await unchanged(rel === './' ? './index.html' : rel);
        if (kept) { await cache.put(abs(rel), kept); return; }
        const res = await fetch(new Request(abs(rel), { cache: 'reload' }));
        if (res.ok) await cache.put(abs(rel), res);
        else console.warn('[sw] precache skipped', rel, res.status);
      } catch (e) {
        console.warn('[sw] precache failed', rel, e && e.message);
      }
    };
    for (let i = 0; i < PRECACHE.length; i += CHUNK) await Promise.all(PRECACHE.slice(i, i + CHUNK).map(one));
    await cache.put(abs(HASH_KEY), new Response(JSON.stringify(HASHES), { headers: { 'Content-Type': 'application/json' } }));
    // The data the app fetched as it went (the dictionary's generated banks …): every file still the same is
    // carried over, so a section does not download it again after an update.
    const runtime = await caches.open(RUNTIME);
    for (const { cache: c, hashes } of earlier) {
      for (const req of await c.keys()) {
        if (req.url === abs(HASH_KEY) || await cache.match(req, { ignoreSearch: true }) || await runtime.match(req, { ignoreSearch: true })) continue;
        let rel;
        try { rel = relOf(req.url); } catch { continue; }
        if (HASHES[rel] && hashes[rel] === HASHES[rel]) { const r = await c.match(req); if (r) await runtime.put(req, r); }
      }
    }
    await runtime.put(abs(HASH_KEY), new Response(JSON.stringify(HASHES), { headers: { 'Content-Type': 'application/json' } }));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names
      .filter((n) => n.startsWith('latin103-') && n !== SHELL && n !== RUNTIME)
      .map((n) => caches.delete(n)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  const type = event.data && event.data.type;
  if (type === 'skip-waiting') self.skipWaiting();
  if (type === 'clear-runtime') event.waitUntil(caches.delete(RUNTIME).then(() => caches.open(RUNTIME)));
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;          // Supabase etc.: network only, never cached
  if (!url.pathname.startsWith(scopePath())) return;        // outside the app folder (dev fixtures)
  event.respondWith(cacheFirst(req));
});

function scopePath() {
  const p = new URL('./', self.location.href).pathname;
  return p;
}

async function cacheFirst(req) {
  const shell = await caches.open(SHELL);
  const key = req.mode === 'navigate' ? abs('./index.html') : req;
  let hit = await shell.match(key, { ignoreSearch: true });
  if (hit) return hit;
  const runtime = await caches.open(RUNTIME);
  hit = await runtime.match(req, { ignoreSearch: true });
  if (hit) return hit;
  try {
    const res = await fetch(req);
    if (res.ok && res.type === 'basic') runtime.put(req, res.clone()).catch(() => {});
    return res;
  } catch (e) {
    if (req.mode === 'navigate') {
      const index = await shell.match(abs('./index.html'));
      if (index) return index;
    }
    throw e;
  }
}
