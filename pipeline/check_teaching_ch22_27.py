"""Validator for the chapter 22-27 teaching sentences and lesson `teach` blocks.

Contract: docs/GRAMMAR-CONTRACT.md, "# Teaching rebuild (2026-09-09)", sections 1 and 2.

Covers the eight skills written for chapters 22-27:
  perfect-deponent, future-participle, future-infinitive, pluperfect,
  ablative-comparison, deponent-imperatives, gerund, present-subjunctive.

What it checks, per skill:
  * app/data/grammar/sentences/<skill>.json is valid JSON with the contract shape,
    and its `skill` / `chapter` agree with skills.json
  * every printed word is a real inflected form of a word taught in a deck at or
    before the skill's chapter - the forms are GENERATED by pipeline/latin_forms.py
    from the glossary entry, so this tests morphology as well as membership - or a
    proper name of the book's cast, or the construction's own function word; every
    exception is listed with its justification
  * 5-8 printed words, or the sentence carries its own `note` saying why not, and
    the declared `words` count is the real one
  * `focus` occurs verbatim in `la`; `en`, `step`, `stage`, `kinds` present; every
    declared kind is one the skill declares; at least twelve sentences
  * the gloss has one entry per printed word, in order
  * every sentence id is unique, within the file and across all files checked
  * app/data/grammar/lessons/<skill>.json carries a `teach` block of 4-6 steps,
    numbered 1..n, each with a title, a `say`, and exactly one `check`
  * every sentence id a step names exists, and every step has a sentence of its own
  * every paradigm key used is in the paradigm_keys map in skills.json AND in the
    skill's own `paradigms` list
  * every paradigm cell key parses in the repo's cell-key convention, extended here
    to the gerund and imperative cells that paradigms.js already emits
  * the skill's `plain` string appears verbatim in the first teach step
  * core / more / sources of the lesson are still present and untouched in shape

Usage:  PYTHONIOENCODING=utf-8 python pipeline/check_teaching_ch22_27.py [skill ...]
"""

